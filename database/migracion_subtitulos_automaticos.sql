-- ================================================================
-- Migración: subtítulos automáticos para revisión del instructor (RF-037 / HU-037)
-- Para bases de datos YA creadas (el esquema completo ya incluye la tabla).
-- Idempotente: se puede ejecutar más de una vez.
--
-- Regla de negocio:
--   * Al guardar un video o podcast con enlace se genera en segundo plano un borrador de
--     subtítulos (ServicioTranscripcion: «prueba» o whisper.cpp local).
--   * El instructor lo corrige o sube un .srt/.vtt; solo al aprobarlo se crea el recurso de
--     subtítulos (video) y la transcripción si falta. Sin aprobación no se puede publicar.
-- ================================================================
CREATE TABLE IF NOT EXISTS subtitulos_borrador (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenido_id INT NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    origen VARCHAR(15) NOT NULL DEFAULT 'AUTOMATICO',
    url_medio VARCHAR(500),
    vtt TEXT,
    error VARCHAR(500),
    fecha_solicitud TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    fecha_generacion TIMESTAMP(0),
    aprobado_por INT,
    fecha_aprobacion TIMESTAMP(0),
    CONSTRAINT uq_subtitulo_borrador_contenido UNIQUE (contenido_id),
    CONSTRAINT ck_subtitulo_borrador_estado CHECK (estado IN ('PENDIENTE', 'GENERANDO', 'LISTO', 'FALLIDO', 'APROBADO')),
    CONSTRAINT ck_subtitulo_borrador_origen CHECK (origen IN ('AUTOMATICO', 'MANUAL')),
    CONSTRAINT fk_subtitulo_borrador_contenido FOREIGN KEY (contenido_id)
        REFERENCES contenidos(id) ON UPDATE NO ACTION ON DELETE CASCADE,
    CONSTRAINT fk_subtitulo_borrador_aprobador FOREIGN KEY (aprobado_por)
        REFERENCES usuarios(id) ON UPDATE NO ACTION ON DELETE SET NULL
);
