-- ================================================================
-- Migración: desbloqueo de cuenta mediante enlace al correo (RF-043 / HU-043)
-- Para bases de datos YA creadas (el esquema completo ya incluye la tabla).
-- Idempotente: se puede ejecutar más de una vez.
--
-- Regla de negocio:
--   * Al bloquearse la cuenta por 5 intentos fallidos se envía un enlace de un solo uso
--     que vence a los 15 minutos. Solo se guarda el hash SHA-256 del token.
--   * Tras 3 bloqueos en 24 horas la cuenta queda bloqueada hasta que la desbloquee
--     un administrador (lo aplica la aplicación; no requiere columnas nuevas).
-- ================================================================
CREATE TABLE IF NOT EXISTS tokens_desbloqueo (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INT NOT NULL,
    token_hash VARCHAR(128) NOT NULL,
    fecha_creacion TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    fecha_expiracion TIMESTAMP(0) NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    ip_origen VARCHAR(45),
    CONSTRAINT uq_token_desbloqueo_hash UNIQUE (token_hash),
    CONSTRAINT fk_token_desbloqueo_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id) ON UPDATE NO ACTION ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_token_desbloqueo_usuario ON tokens_desbloqueo (usuario_id, usado);
