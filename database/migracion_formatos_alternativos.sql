-- ================================================================
-- Migración: contenidos en formatos alternativos (RF-032 / HU-032)
-- Para bases de datos YA creadas (el esquema completo ya incluye la tabla).
-- Idempotente: se puede ejecutar más de una vez.
--
-- Regla de negocio:
--   * Los contenidos de lectura se ofrecen en MP3, EPUB, HTML accesible y braille (BRF).
--   * Lo ya generado se reutiliza mientras el texto no cambie (huella SHA-256); lo nuevo se
--     genera en segundo plano y se avisa al estudiante. Cada descarga queda en auditoría.
--   * Videos y simulaciones solo ofrecen su transcripción.
--   * Los archivos se guardan en ${vlearning.uploads.dir}/formatos/{contenido}/.
-- ================================================================
CREATE TABLE IF NOT EXISTS formatos_alternativos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenido_id INT NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    ruta_archivo VARCHAR(300),
    huella_contenido VARCHAR(64),
    tamano_bytes BIGINT,
    error VARCHAR(500),
    fecha_solicitud TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    generado_en TIMESTAMP(0),
    CONSTRAINT uq_formato_alternativo UNIQUE (contenido_id, tipo),
    CONSTRAINT ck_formato_alternativo_tipo CHECK (tipo IN ('MP3', 'EPUB', 'HTML', 'BRF')),
    CONSTRAINT ck_formato_alternativo_estado CHECK (estado IN ('PENDIENTE', 'GENERANDO', 'LISTO', 'FALLIDO')),
    CONSTRAINT fk_formato_alternativo_contenido FOREIGN KEY (contenido_id)
        REFERENCES contenidos(id) ON UPDATE NO ACTION ON DELETE CASCADE
);
