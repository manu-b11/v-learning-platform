-- ================================================================
-- Migración: acomodaciones de evaluación por estudiante (RF-041 / HU-041)
-- Para bases de datos YA creadas (el esquema completo ya incluye estos cambios).
-- Idempotente: se puede ejecutar más de una vez.
--
-- Regla de negocio:
--   * Instructor o administrador asignan a un estudiante inscrito un multiplicador de tiempo
--     (1,5x o 2x), tiempo ilimitado, intentos extra, fecha límite especial y vigencia.
--   * Se aplican a todas las evaluaciones del curso, también a las creadas después.
--   * El servidor aplica el MAYOR entre el multiplicador y el tiempo adicional del perfil
--     (RF-021); no los suma. Una acomodación vencida no se aplica.
-- ================================================================
CREATE TABLE IF NOT EXISTS acomodaciones (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscripcion_id INT NOT NULL,
    multiplicador_tiempo DECIMAL(3,2),
    tiempo_ilimitado BOOLEAN NOT NULL DEFAULT FALSE,
    intentos_extra INT NOT NULL DEFAULT 0,
    fecha_limite_especial TIMESTAMP(0),
    minutos_ampliacion INT NOT NULL DEFAULT 0,
    vigente_hasta DATE,
    creada_por INT NOT NULL,
    fecha_creacion TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_acomodacion_multiplicador CHECK (multiplicador_tiempo IS NULL OR multiplicador_tiempo IN (1.50, 2.00)),
    CONSTRAINT ck_acomodacion_intentos CHECK (intentos_extra BETWEEN 0 AND 5),
    CONSTRAINT ck_acomodacion_ampliacion CHECK (minutos_ampliacion BETWEEN 0 AND 60),
    CONSTRAINT fk_acomodacion_inscripcion FOREIGN KEY (inscripcion_id)
        REFERENCES inscripciones(id) ON UPDATE NO ACTION ON DELETE CASCADE,
    CONSTRAINT fk_acomodacion_creada_por FOREIGN KEY (creada_por)
        REFERENCES usuarios(id) ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_acomodacion_activa ON acomodaciones (inscripcion_id) WHERE activa;
