-- ================================================================
-- Migración: verificador de accesibilidad del contenido (RF-049 / HU-049, RF-039 / HU-039)
-- Para bases de datos YA creadas (el esquema completo ya incluye la tabla).
-- Idempotente: se puede ejecutar más de una vez.
--
-- Regla de negocio:
--   * El instructor ve en el editor los problemas de accesibilidad mientras escribe.
--   * Al publicar un contenido o un curso se ejecuta la verificación completa: los hallazgos
--     BLOQUEANTES (imagen sin texto alternativo, video sin subtítulos o transcripción, audio o
--     podcast sin transcripción) impiden publicar (HTTP 422); las ADVERTENCIAS no.
--   * Se conserva un informe por contenido; los hallazgos corregidos quedan como resueltos.
-- ================================================================
CREATE TABLE IF NOT EXISTS hallazgos_accesibilidad (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenido_id INT NOT NULL,
    regla VARCHAR(40) NOT NULL,
    criterio_wcag VARCHAR(20) NOT NULL,
    severidad VARCHAR(15) NOT NULL,
    mensaje VARCHAR(500) NOT NULL,
    como_corregir VARCHAR(500) NOT NULL,
    resuelto BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_verificacion TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    fecha_resolucion TIMESTAMP(0),
    CONSTRAINT ck_hallazgo_severidad CHECK (severidad IN ('BLOQUEANTE', 'ADVERTENCIA')),
    CONSTRAINT fk_hallazgo_contenido FOREIGN KEY (contenido_id)
        REFERENCES contenidos(id) ON UPDATE NO ACTION ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_hallazgos_contenido ON hallazgos_accesibilidad (contenido_id, resuelto);
